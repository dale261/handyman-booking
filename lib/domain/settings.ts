export function normalizeSettings(input: Partial<Settings> | null | undefined): Settings {
  const d = DEFAULT_SETTINGS;
  const src = input ?? {};
  const counties = Array.isArray(src.premiumCounties)
    ? src.premiumCounties.map((c) => String(c).trim()).filter(Boolean)
    : d.premiumCounties;
  return {
    shopAddress: String(src.shopAddress || d.shopAddress),
    shopLat: num(src.shopLat, d.shopLat),
    shopLng: num(src.shopLng, d.shopLng),
    ownerNotifyEmail: String(src.ownerNotifyEmail ?? ""),
    rrpCertified: Boolean(src.rrpCertified),
    premiumEnabled: src.premiumEnabled !== false,
    premiumMultiplier: num(src.premiumMultiplier, d.premiumMultiplier),
    premiumCounties: counties.length ? counties : d.premiumCounties,
    depositThreshold: num(src.depositThreshold, d.depositThreshold),
    cancelFee: num(src.cancelFee, d.cancelFee),
    holdHours: Math.max(1, Math.round(num(src.holdHours, d.holdHours))),
    bufferMinutes: Math.max(0, Math.round(num(src.bufferMinutes, d.bufferMinutes))),
    roadFactor: num(src.roadFactor, d.roadFactor),
    driveFactor: num(src.driveFactor, d.driveFactor),
    drivePadMinutes: Math.round(num(src.drivePadMinutes, d.drivePadMinutes)),
    mileRate: num(src.mileRate, d.mileRate),
    travelMinimum: num(src.travelMinimum, d.travelMinimum),
    hourly: num(src.hourly, d.hourly),
    minimumJob: num(src.minimumJob, d.minimumJob),
    helperRate: num(src.helperRate, d.helperRate),
    helperMax: Math.max(1, Math.round(num(src.helperMax, d.helperMax))),
    helperMaxHours: Math.max(1, Math.round(num(src.helperMaxHours, d.helperMaxHours))),
    paintSqft: num(src.paintSqft, d.paintSqft),
    paintCeiling: num(src.paintCeiling, d.paintCeiling),
    paintDoor: num(src.paintDoor, d.paintDoor),
    paintColor: num(src.paintColor, d.paintColor),
    paintCrewSize: Math.max(1, Math.round(num(src.paintCrewSize, d.paintCrewSize))),
    yardCrewSize: Math.max(1, Math.round(num(src.yardCrewSize, d.yardCrewSize))),
    tvSmall: num(src.tvSmall, d.tvSmall),
    tvMid: num(src.tvMid, d.tvMid),
    tvLarge: num(src.tvLarge, d.tvLarge),
    tvConceal: num(src.tvConceal, d.tvConceal),
    tvPlaster: num(src.tvPlaster, d.tvPlaster),
    tvBrick: num(src.tvBrick, d.tvBrick),
    tvRaceway: num(src.tvRaceway, d.tvRaceway),
    asmSmall: num(src.asmSmall, d.asmSmall),
    asmMedium: num(src.asmMedium, d.asmMedium),
    asmLarge: num(src.asmLarge, d.asmLarge),
    blindsEach: num(src.blindsEach, d.blindsEach),
    urgency: num(src.urgency, d.urgency),
    pickup: num(src.pickup, d.pickup),
    haul: num(src.haul, d.haul),
    height9: num(src.height9, d.height9),
    height11: num(src.height11, d.height11),
    condFair: num(src.condFair, d.condFair),
    condPoor: num(src.condPoor, d.condPoor),
    deepClean: num(src.deepClean, d.deepClean),
    onsitePaint: Math.max(30, Math.round(num(src.onsitePaint, d.onsitePaint))),
    onsiteTv: Math.max(30, Math.round(num(src.onsiteTv, d.onsiteTv))),
    onsiteBlinds: Math.max(30, Math.round(num(src.onsiteBlinds, d.onsiteBlinds))),
    onsiteFurniture: Math.max(30, Math.round(num(src.onsiteFurniture, d.onsiteFurniture))),
    onsiteYard: Math.max(30, Math.round(num(src.onsiteYard, d.onsiteYard))),
    onsiteClean: Math.max(30, Math.round(num(src.onsiteClean, d.onsiteClean))),
    onsiteOther: Math.max(30, Math.round(num(src.onsiteOther, d.onsiteOther))),
    slotStartMin: Math.round(num(src.slotStartMin, d.slotStartMin)),
    slotEndMin: Math.round(num(src.slotEndMin, d.slotEndMin)),
    slotStepMin: Math.max(15, Math.round(num(src.slotStepMin, d.slotStepMin))),
    builderThreshold: num(src.builderThreshold, d.builderThreshold),
  };
}
